#!/usr/bin/env python3
"""Write THIRD_PARTY_NOTICES.md from the lock file and the licence files at the pinned commits (nothing typed by hand
except the structure). Run by reproduce.py so the file cannot drift from the pins."""
import common as c
import frameworks as fwm  # noqa: F401

OUT = c.ROOT / "THIRD_PARTY_NOTICES.md"
MITRE_LINE = "© 2026 The MITRE Corporation. This work is reproduced and distributed with the permission of The MITRE Corporation."
TOU = "https://attack.mitre.org/resources/legal-and-branding/terms-of-use/"


def licence_of(repo_dir: str, sha: str, name: str = "LICENSE") -> str | None:
    return c.show(c.CACHE / repo_dir, sha, name)


def main() -> None:
    full = c.load_yaml(c.LOCK_FILE)
    lock = c.public_lock(full)                      # hidden settings (config/publish.yml) are not named here
    fw = lock["frameworks"]
    la = [s for s in lock["sources"] if s["setting"] == "linuxarena"]
    texts = {s["environment"]: licence_of(s["repo"].split("/")[1], s["sha"]) for s in la}
    distinct = sorted({t for t in texts.values()})
    assert len(distinct) == 1, "the 10 LinuxArena licence files differ; list them separately"
    mit = distinct[0].strip()
    copyright_line = next(l for l in mit.splitlines() if l.lower().startswith("copyright"))
    attack_lic = (c.DATA / "legal" / "attack_licence.txt").read_text(encoding="utf-8").strip()
    atlas_dir = c.ROOT / ".cache" / "frameworks" / "atlas-data"
    atlas_lic_first = c.show(atlas_dir, fw["atlas"]["sha"], "LICENSE").strip().splitlines()[0]
    atlas_copy = next(l for l in c.show(atlas_dir, fw["atlas"]["sha"], "LICENSE").splitlines() if l.startswith("Copyright"))
    direct = [s for s in lock["sources"] if s["setting"] in ("refactor_arena", "vllm")]
    extras = [s for s in full["sources"] if s["setting"] == "linuxarena-extras"] if c.publish_extras() else []
    man = {m["setting"]: m for m in lock["manifests"]}
    show_extras = c.publish_extras()
    L = ["# Third-party notices", "",
         "This project reuses material from the sources below. Each section gives the licence, the copyright line, and what we do with the material.",
         "Commit SHAs come from `data/sources.lock.yml`. This file is generated by `scripts/build_notices.py`.", "",
         "## MITRE ATT&CK®", "",
         f"- {MITRE_LINE}",
         f"- Terms of Use: <{TOU}>",
         f"- Source of the data: `mitre-attack/attack-stix-data`, tag `{fw['attack']['tag']}`, commit `{fw['attack']['sha']}`, file `{fw['attack']['path']}` (SHA-256 `{fw['attack']['sha256']}`).",
         "- What we do: we use technique and tactic IDs and names, and tactic-to-technique relationships, to label tasks and to draw the matrix and Navigator layers.",
         "- **Not affiliated with or endorsed by The MITRE Corporation.**", "",
         "MITRE's licence and disclaimers, reproduced exactly from the `LICENSE.txt` in that repository at that commit:", "",
         "```", attack_lic, "```", "",
         "## MITRE ATLAS", "",
         f"- Licence: Apache License 2.0 (first line of the licence file: \"{atlas_lic_first}\"). {atlas_copy}.",
         f"- Source: `mitre-atlas/atlas-data`, tag `{fw['atlas']['tag']}`, commit `{fw['atlas']['sha']}`, file `{fw['atlas']['path']}` (SHA-256 `{fw['atlas']['sha256']}`).",
         "- That repository has no `NOTICE` file at this commit, so there is no NOTICE text to reproduce.",
         "- What we do: we extract tactic and technique names and the technique-to-tactic relationships into `data/generated/frameworks.json` (a changed format, no change of meaning). Licence text: <https://www.apache.org/licenses/LICENSE-2.0>.", "",
         "## MITRE ATT&CK® Navigator layer format", "",
         "- Licence: Apache License 2.0. The Navigator repository's `NOTICE.txt` reads: \"Copyright 2025 The MITRE Corporation\".",
         f"- Source: `mitre-attack/attack-navigator`, commit `{lock['references']['attack_navigator']['sha']}`, file `{lock['references']['attack_navigator']['layer_spec']}`.",
         "- What we do: we write layer files that follow the documented format and check them against it. No Navigator code is included.", "",
         "## LinuxArena environment repositories (10): MIT", "",
         f"Goal texts of the tasks in these repositories are reproduced, so the licence notice is reproduced as the licence requires. Every one of the 10 licence files is identical. Copyright line: **{copyright_line}**.", "",
         "| Environment | Repository | Tag | Commit |", "|---|---|---|---|"]
    L += [f"| {s['environment']} | `{s['repo']}` | {s['tag']} | `{s['sha']}` |" for s in la]
    L += ["", "```", mit, "```", "",
          "## Refactor Arena and ct-vllm: MIT (declared, no licence file)", "",
          "These repositories declare `license = \"MIT\"` in `pyproject.toml` and have no `LICENSE` file, so there is no copyright line to reproduce. We treat them as MIT on the strength of that declaration. "
          "**This is a claim we could not confirm with a licence file.**", "", "| Repository | Tag | Commit |", "|---|---|---|"]
    L += [f"| `{s['repo']}` | {s['tag']} | `{s['sha']}` |" for s in direct]
    if show_extras:
        L += ["", "## ct-linuxarena and ct-linuxarena-extras manifests", "",
              f"- `{man['linuxarena']['repo']}` at `{man['linuxarena']['tag']}` (`{man['linuxarena']['sha']}`) and `{man['linuxarena-extras']['repo']}` at `{man['linuxarena-extras']['tag']}` (`{man['linuxarena-extras']['sha']}`): MIT declared in `pyproject.toml`. "
              "We read only the `envs.lock.yml` file listing which environment repositories and commits to use.", "",
              "## LinuxArena extras environment repositories (4): no licence", "",
              "These four repositories have no licence file and no licence declaration at the top level:", ""]
        L += [f"- `{s['repo']}`, tag {s['tag']}, commit `{s['sha']}`" for s in extras]
        L += ["", "**We do not copy their goal text.** For each of their tasks we store only the task ID, a link to the source file at the pinned commit, and a short summary (20 words or fewer) written by us and marked \"our summary\". "
              "A permission request to the maintainers is drafted in `docs/MAINTAINER_PERMISSION_REQUEST.md`; it has not been sent. A test (`tests/test_no_leak.py`) fails if any run of six words from their text appears in this repository.", ""]
    else:
        L += ["", "## ct-linuxarena manifest", "",
              f"- `{man['linuxarena']['repo']}` at `{man['linuxarena']['tag']}` (`{man['linuxarena']['sha']}`): MIT declared in `pyproject.toml`. "
              "We read only the `envs.lock.yml` file listing which environment repositories and commits to use.", "",
              "## LinuxArena extras", "", "LinuxArena extras is not included in v0.1, pending permission from its maintainers. Nothing from it is reproduced here.", ""]
    L += ["## Control Tower documentation", "",
          f"The definitions in the Guide's glossary were checked against the Control Tower docs (`linuxarena/control-tower`, commit `{lock['references']['control_tower_docs']['sha']}`, MIT, Copyright (c) 2025 LinuxArena). "
          "We paraphrase them and quote only short phrases. See `docs/GLOSSARY_CHECK.md`.", ""]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT.name}: {len(la)} LinuxArena env licences identical")


if __name__ == "__main__":
    main()
